for (const strings of [archiveStrings, processStrings, taskStrings]) {
  for (const [code, entries] of Object.entries(strings)) dictionaries[code] = { ...dictionaries[code], ...entries };
}

export const lang = navigator.language.toLowerCase().startsWith("ru") ? "ru" : "en";

export function addStrings(strings: Record<string, Strings>): void {
  for (const [code, entries] of Object.entries(strings)) {
    dictionaries[code] = { ...dictionaries[code], ...entries };
  }
}

/** Whether a string has a text in the user's language or in English. */
export function known(key: string): boolean {
  return key in (dictionaries[lang] ?? {}) || key in dictionaries.en;
}

export function t(key: string, vars: Record<string, string | number> = {}): string {
  const text = dictionaries[lang]?.[key] ?? dictionaries.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? `{${name}}`));
}
